"""Self-checking testbench for ``mlkem_ntt_core``.

Expected transforms come from ``fips203_oracle`` (computed here in Python and embedded as
data).  Besides the results the bench checks: exact kernel cycle counts (measured by
counting clocks between start and done, and against the core's own counter), the done
pulse width, that a start while busy is ignored, recovery after reset in flight, and --
every clock, in every transform -- that each lane's valid output lines up with the write
enables the ROM schedules for it.
"""
from . import fips203_oracle as O
from .rtlgen import build
from .vectors import test_vectors


def emit_core_tb(cfg, n_random=6):
    sf, si, wf, wi = build(cfg)
    L, B, BB = cfg.lanes, cfg.banks, cfg.bank_bits
    vecs = test_vectors(n_random)
    names = list(vecs)
    nv = len(names)
    lines = []
    for vi, name in enumerate(names):
        f = vecs[name]
        fwd, inv = O.ntt(f), O.ntt_inv(f)
        for i in range(256):
            lines.append(f"        vin[{vi * 256 + i}] = {f[i]}; vfw[{vi * 256 + i}] = {fwd[i]}; "
                         f"viv[{vi * 256 + i}] = {inv[i]};")
    return f"""\
// GENERATED by cmtz.accel.mlkem_ntt.tb_core -- do not edit.  lanes = {L}, {cfg.reduction}
`timescale 1ns/1ps
module mlkem_ntt_core_tb;
    localparam NV = {nv}, L = {L}, B = {B}, BB = {BB};
    localparam EXP_F = {len(wf) + cfg.overhead}, EXP_I = {len(wi) + cfg.overhead};
    reg clk = 0, rst = 1;
    always #5 clk = ~clk;
    reg start = 0, inv = 0, h_we = 0;
    reg [7:0] h_idx = 0;
    reg [11:0] h_wdata = 0;
    wire busy, done; wire [15:0] cycles; wire [11:0] h_rdata;
    mlkem_ntt_core dut (.clk(clk), .rst(rst), .start(start), .inv(inv), .busy(busy), .done(done),
                        .cycles(cycles), .h_we(h_we), .h_idx(h_idx), .h_wdata(h_wdata),
                        .h_rdata(h_rdata));

    reg [11:0] vin [0:NV*256-1];
    reg [11:0] vfw [0:NV*256-1];
    reg [11:0] viv [0:NV*256-1];
    initial begin
{chr(10).join(lines)}
    end

    integer errors = 0, checks = 0;
    integer vi, i, n;
    integer measured;

    // ---- every-clock lane-valid / write-enable alignment monitor ----
    reg [L-1:0] vo_now, vo_q;
    reg [L-1:0] exp_v;
    reg [BB-1:0] wsel_q [0:B-1];
    integer mon_bad = 0, mon_cycles = 0;
    always @(posedge clk) begin
        vo_q <= vo_now;
{chr(10).join(f"        wsel_q[{k}] <= dut.wsel{k};" for k in range(B))}
    end
{_monitor(cfg)}

    task tick; begin @(posedge clk); #1; end endtask

    task host_write(input integer idx, input integer val);
        begin h_we <= 1; h_idx <= idx; h_wdata <= val; tick; h_we <= 0; end
    endtask

    task load(input integer v);
        begin
            for (i = 0; i < 256; i = i + 1) host_write(i, vin[v * 256 + i]);
        end
    endtask

    reg [11:0] got;
    task expect_mem(input integer which, input integer v, input [8*12-1:0] tag);
        begin
            for (i = 0; i < 256; i = i + 1) begin
                h_idx <= i; tick;                // h_rdata is valid RD_LAT clocks after h_idx
{'                tick;' * (cfg.rd_lat - 1)}
                got = h_rdata;
                checks = checks + 1;
                if (which == 0 && got !== vfw[v * 256 + i] ||
                    which == 1 && got !== viv[v * 256 + i] ||
                    which == 2 && got !== vin[v * 256 + i]) begin
                    errors = errors + 1;
                    if (errors < 12) $display("FAIL %0s vec %0d idx %0d got %0d", tag, v, i, got);
                end
            end
        end
    endtask

    // run one transform; measures clocks from the start edge to the done edge
    task run_tf(input integer mode, input integer expect_cycles, input integer poke_start);
        integer c, donewidth;
        begin
            inv <= mode; start <= 1; tick; start <= 0;
            c = 1; donewidth = 0;
            while (!done) begin
                c = c + 1;
                if (poke_start && c == 20) begin start <= 1; inv <= !mode; end   // must be ignored
                else start <= 0;
                tick;
                if (c > 5000) begin $display("FAIL timeout"); $finish; end
            end
            start <= 0;
            measured = c;
            while (done) begin donewidth = donewidth + 1; tick; end
            checks = checks + 1;
            if (c != expect_cycles) begin
                errors = errors + 1; $display("FAIL cycles measured %0d expected %0d", c, expect_cycles);
            end
            if (cycles !== expect_cycles) begin
                errors = errors + 1; $display("FAIL core counter %0d expected %0d", cycles, expect_cycles);
            end
            if (donewidth != 1 || busy !== 1'b0) begin
                errors = errors + 1; $display("FAIL done width %0d busy %b", donewidth, busy);
            end
        end
    endtask

    initial begin
        repeat (4) tick;
        rst <= 0; tick;
        for (vi = 0; vi < NV; vi = vi + 1) begin
            load(vi);
            run_tf(0, EXP_F, vi == 1);
            expect_mem(0, vi, "forward");
            run_tf(1, EXP_I, 0);                 // inverse of the forward result
            expect_mem(2, vi, "roundtrip");
            load(vi);
            run_tf(1, EXP_I, vi == 2);           // inverse of the raw polynomial
            expect_mem(1, vi, "inverse");
        end
        // reset in flight: abort a transform, then a clean run must still be right
        load(3);
        inv <= 0; start <= 1; tick; start <= 0;
        repeat (40) tick;
        rst <= 1; tick; tick; rst <= 0; tick; tick;
        if (busy !== 1'b0) begin errors = errors + 1; $display("FAIL busy after reset"); end
        load(3);
        run_tf(0, EXP_F, 0);
        expect_mem(0, 3, "post-reset forward");
        if (mon_bad != 0) begin errors = errors + 1; $display("FAIL lane valid misaligned %0d times", mon_bad); end
        if (errors == 0)
            $display("PASS mlkem_ntt_core lanes=%0d: %0d vectors, %0d checks, fwd %0d cyc, inv %0d cyc, valid monitor %0d clocks",
                     L, NV, checks, EXP_F, EXP_I, mon_cycles);
        else $display("FAIL mlkem_ntt_core: %0d errors", errors);
        $finish;
    end
endmodule
"""


def _monitor(cfg):
    """Lane valid output vs the write enable/select the ROM issues for it."""
    L, B = cfg.lanes, cfg.banks
    vo = ", ".join(f"dut.vo{l}" for l in reversed(range(L)))
    exp = []
    for l in range(L):
        ws = (lambda k: f"wsel_q[{k}]") if cfg.wreg else (lambda k: f"dut.wsel{k}")
        terms = [f"(dut.wvb{k} && dut.ctl_we{k} && ({ws(k)} >> 1) == {l})" for k in range(B)]
        exp.append(f"        exp_v[{l}] = " + " || ".join(terms) + ";")
    cmp_vo = "vo_q" if cfg.wreg else "vo_now"
    return f"""\
    always @* begin
        vo_now = {{{vo}}};
{chr(10).join(exp)}
    end
    always @(posedge clk) if (!rst) begin
        mon_cycles = mon_cycles + 1;
        if ({cmp_vo} !== exp_v) begin
            mon_bad = mon_bad + 1;
            if (mon_bad < 5) $display("FAIL lane valid mismatch t=%0t vo=%b exp=%b", $time, {cmp_vo}, exp_v);
        end
    end"""
