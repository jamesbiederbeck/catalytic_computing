"""UART board wrapper for the NTT core.

The core and the UART share one clock (the PLL output on hardware).  The transform runs
entirely on chip; the UART only loads coefficients, starts, reads results and reads
counters, and is never inside the timed loop.

Protocol (115200 8N1, all multi-byte values little endian):

  'P'            -> 'M' 'K' lanes reduction(0 mont, 1 barrett) cfg_version
  'W' + 512 B    -> 'K'          write 256 coefficients, 2 bytes each (low, high nibble)
  'R'            -> 512 B        read them back
  'F' | 'I'      -> 'K' c_lo c_hi        one forward / inverse transform; core cycle counter
  'B' n          -> 'K' t0 t1 t2         n back-to-back forward transforms; total clocks from
                                         the first start to the last done (24 bit)
  'Q'            -> 'K' f0 f1 f2         core-clock cycles counted in the last full 1 ms of the
                                         27 MHz crystal (so f is the core clock in kHz)
"""
from pathlib import Path

from .config import NTTConfig

_UART = Path(__file__).resolve().parents[2] / "backends" / "verilog_uart_modules.v"


def uart_modules():
    return _UART.read_text()


def pll_hz(pll):
    idiv, fbdiv, odiv = pll
    return 27_000_000 * (fbdiv + 1) / (idiv + 1)


def emit_top(cfg: NTTConfig, baud=115200):
    hz = pll_hz(cfg.pll) if cfg.pll else 27_000_000
    cpb = round(hz / baud)
    lanes = cfg.lanes
    red = 0 if cfg.reduction == "montgomery" else 1
    if cfg.pll:
        idiv, fbdiv, odiv = cfg.pll
        pll_inst = f"""\
    wire lock;
    rPLL #(
        .FCLKIN("27"),
        .IDIV_SEL({idiv}),
        .FBDIV_SEL({fbdiv}),
        .ODIV_SEL({odiv}),
        .DEVICE("GW2A-18C")
    ) pll (
        .CLKIN(clk27), .CLKFB(1'b0), .RESET(1'b0), .RESET_P(1'b0),
        .FBDSEL(6'b0), .IDSEL(6'b0), .ODSEL(6'b0),
        .PSDA(4'b0), .DUTYDA(4'b0), .FDLY(4'b0),
        .CLKOUT(fclk), .LOCK(lock), .CLKOUTP(), .CLKOUTD(), .CLKOUTD3()
    );"""
    else:
        pll_inst = "    wire lock = 1'b1;\n    assign fclk = clk27;"
    return f"""\
// GENERATED by cmtz.accel.mlkem_ntt.uart_top -- do not edit.
// Board top: UART front end for mlkem_ntt_core.  Core clock {hz / 1e6:.3f} MHz
// ({'rPLL from 27 MHz' if cfg.pll else '27 MHz crystal, no PLL'}).  See uart_top.py for the protocol.
module mlkem_ntt_uart #(
    parameter CLKS_PER_BIT = {cpb}
) (
    input  wire       clk27,
    input  wire       rx,
    output wire       tx,
    output wire [5:0] leds
);
    wire fclk;
`ifdef SYNTHESIZE
{pll_inst}
`else
    wire lock = 1'b1;
    assign fclk = clk27;
`endif

    // ---- power-on reset ----
    reg [3:0] rst_cnt = 4'd15;
    wire rst = (rst_cnt != 0) || !lock;
    always @(posedge fclk) if (rst_cnt != 0) rst_cnt <= rst_cnt - 1'b1;

    // ---- core clock measurement against the 27 MHz crystal ----
    reg [14:0] gate_cnt = 0;
    reg        gate = 1'b0;
    always @(posedge clk27) begin
        if (gate_cnt == 15'd26999) begin gate_cnt <= 0; gate <= ~gate; end
        else gate_cnt <= gate_cnt + 1'b1;
    end
    reg g_m = 0, g_s = 0, g_q = 0;
    reg [23:0] fcnt = 0, fcount = 0;
    always @(posedge fclk) begin
        g_m <= gate; g_s <= g_m; g_q <= g_s;
        if (g_s != g_q) begin fcount <= fcnt; fcnt <= 24'd1; end   // one 1 ms window per edge
        else fcnt <= fcnt + 1'b1;
    end

    // ---- UART ----
    wire [7:0] rx_data; wire rx_strobe;
    reg  [7:0] tx_data = 0; reg tx_go = 1'b0; wire tx_busy;
    uart_rx #(.CLKS_PER_BIT(CLKS_PER_BIT)) urx (.clk(fclk), .rx(rx), .data(rx_data), .strobe(rx_strobe));
    uart_tx #(.CLKS_PER_BIT(CLKS_PER_BIT)) utx (.clk(fclk), .data(tx_data), .start(tx_go), .tx(tx), .busy(tx_busy));

    localparam S_IDLE = 0, S_SEND = 1, S_W_LO = 2, S_W_HI = 3, S_R_WAIT = 4, S_R_SEND = 5,
               S_RUN = 6, S_B_ARG = 7, S_B_RUN = 8;
    reg [3:0] st = S_IDLE, ret = S_IDLE;

    // ---- core ----
    reg  c_start = 1'b0, c_inv = 1'b0, h_we = 1'b0;
    reg  [7:0] h_idx = 0; reg [11:0] h_wdata = 0;
    wire c_busy, c_done; wire [15:0] c_cycles; wire [11:0] h_rdata;
    reg  [7:0] reps = 0;
    wire b_again = (st == S_B_RUN) && c_done && (reps != 8'd1);   // next transform starts in the done clock
    mlkem_ntt_core core (.clk(fclk), .rst(rst), .start(c_start | b_again), .inv(c_inv), .busy(c_busy),
                         .done(c_done), .cycles(c_cycles), .h_we(h_we), .h_idx(h_idx),
                         .h_wdata(h_wdata), .h_rdata(h_rdata));

    // ---- command state machine ----
    reg [7:0] sendbuf [0:4];
    reg [3:0] sn = 0, si = 0;
    reg [8:0] idx = 0;
    reg [7:0] lo = 0;
    reg [23:0] total = 0;
    reg [1:0] wait_c = 0;

    task send1(input [7:0] a);
        begin sendbuf[0] <= a; sn <= 1; si <= 0; ret <= S_IDLE; st <= S_SEND; end
    endtask

    always @(posedge fclk) begin
        tx_go <= 1'b0; c_start <= 1'b0; h_we <= 1'b0;
        if (rst) st <= S_IDLE;
        else case (st)
            S_IDLE: if (rx_strobe) case (rx_data)
                "P": begin sendbuf[0] <= "M"; sendbuf[1] <= "K"; sendbuf[2] <= {lanes};
                           sendbuf[3] <= {red}; sendbuf[4] <= 8'd1; sn <= 5; si <= 0; ret <= S_IDLE; st <= S_SEND; end
                "W": begin idx <= 0; st <= S_W_LO; end
                "R": begin idx <= 0; h_idx <= 0; wait_c <= 0; st <= S_R_WAIT; end
                "F", "I": begin c_inv <= (rx_data == "I"); c_start <= 1'b1; st <= S_RUN; end
                "B": st <= S_B_ARG;
                "Q": begin sendbuf[0] <= "K"; sendbuf[1] <= fcount[7:0]; sendbuf[2] <= fcount[15:8];
                           sendbuf[3] <= fcount[23:16]; sn <= 4; si <= 0; ret <= S_IDLE; st <= S_SEND; end
                default: ;
            endcase
            S_SEND: if (!tx_busy && !tx_go) begin
                tx_data <= sendbuf[si]; tx_go <= 1'b1;
            end else if (tx_go) begin
                si <= si + 1'b1;
                if (si == sn - 1'b1) st <= ret;
            end
            // ---- write 256 x 2 bytes ----
            S_W_LO: if (rx_strobe) begin lo <= rx_data; st <= S_W_HI; end
            S_W_HI: if (rx_strobe) begin
                h_idx <= idx[7:0]; h_wdata <= {{rx_data[3:0], lo}}; h_we <= 1'b1;
                idx <= idx + 1'b1;
                if (idx == 9'd255) send1("K"); else st <= S_W_LO;
            end
            // ---- read 256 x 2 bytes ----
            S_R_WAIT: begin
                wait_c <= wait_c + 1'b1;
                if (wait_c == 2'd1) begin
                    sendbuf[0] <= h_rdata[7:0]; sendbuf[1] <= {{4'd0, h_rdata[11:8]}};
                    sn <= 2; si <= 0; ret <= S_R_SEND; st <= S_SEND;
                end
            end
            S_R_SEND: begin
                idx <= idx + 1'b1;
                if (idx == 9'd255) st <= S_IDLE;
                else begin h_idx <= idx[7:0] + 1'b1; wait_c <= 0; st <= S_R_WAIT; end
            end
            // ---- single transform ----
            S_RUN: if (c_done) begin
                sendbuf[0] <= "K"; sendbuf[1] <= c_cycles[7:0]; sendbuf[2] <= c_cycles[15:8];
                sn <= 3; si <= 0; ret <= S_IDLE; st <= S_SEND;
            end
            // ---- back-to-back forward transforms ----
            S_B_ARG: if (rx_strobe) begin
                reps <= rx_data; total <= 24'd0; c_inv <= 1'b0; c_start <= 1'b1; st <= S_B_RUN;
            end
            S_B_RUN: begin
                total <= total + 1'b1;
                if (c_done) begin
                    if (reps == 8'd1) begin
                        sendbuf[0] <= "K"; sendbuf[1] <= total[7:0]; sendbuf[2] <= total[15:8];
                        sendbuf[3] <= total[23:16];
                        sn <= 4; si <= 0; ret <= S_IDLE; st <= S_SEND;
                    end else begin
                        reps <= reps - 1'b1;
                    end
                end
            end
            default: st <= S_IDLE;
        endcase
    end

    assign leds = ~{{3'b000, c_busy, lock, st != S_IDLE}};
endmodule

{uart_modules()}
"""
