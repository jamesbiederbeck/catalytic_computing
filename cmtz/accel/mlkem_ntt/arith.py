"""ML-KEM modular butterfly: bit-exact Python models and the Verilog emitter.

This is accelerator arithmetic for q = 3329 only.  It is intentionally *not* part of the
Cook-Mertz IR: the IR's ``field(p, q)`` is a tiny working field for roots of unity and has
nothing to do with the ML-KEM modulus.

One lane computes, for 12-bit canonical inputs a, b and a twiddle z read from a table:

  mode 0 (forward, Cooley-Tukey):   t = b*zeta;  o0 = a + t;  o1 = a - t       (mod q)
  mode 1 (inverse, Gentleman-Sande): o0 = (a + b)/2;  o1 = (b - a)*zeta/2      (mod q)

The inverse halves every layer, so after seven layers the result carries the factor
2^-7 = 128^-1 = 3303 that FIPS 203 Algorithm 10 applies at the end.  The normalisation
is therefore free (no extra pass); tests check it against the oracle that multiplies by 3303.

Reduction is Montgomery (R = 2^16, twiddles stored as zeta*R mod q) or Barrett
(e = ((p >> 7) * 80635) >> 21, plain twiddles).  Both take the 24-bit product p of two
canonical 12-bit values and return a value in [0, 2q) that one conditional subtract
canonicalises.  Their ranges are checked exhaustively in tests.

Pipeline (register stages; ``LAT`` clocks from inputs presented to outputs registered):

  R1  x1 = fwd ? b : (b - a) mod q ;  c1 = fwd ? a : a + b       (13 b)   z1, mode1, v1
  R2  p2 = x1 * z1  (24 b, DSP)    ;  c2 = fwd ? a : (a + b) mod q
  R3  reduction step 1             ;  c3 = fwd ? a : (a + b)/2 mod q
        Montgomery  m3 = (p2[15:0] * 3327)[15:0]
        Barrett     e3 = ((p2 >> 7) * 80635) >> 21
  R4  reduction step 2 (u4 in [0, 2q))
        Montgomery  u4 = (p3 + m3 * q) >> 16
        Barrett     u4 = p3 - e3 * q
  R5  t5 = u4 >= q ? u4 - q : u4                                 c5 = c4
  R6  fwd: o0 = (c5 + t5) mod q, o1 = (c5 - t5) mod q ;  inv: o0 = c5, o1 = t5
"""

Q = 3329
LAT = 6                # register stages of the compact lane (depth="compact")


def latency(reduction, depth="deep"):
    """Register stages of a lane.  The deep lane has at most one carry chain (plus a mux)
    per stage and no multiplier except the one DSP product; it is what closes timing on
    the board at high clocks.  The compact lane is the 6-stage original, kept for study."""
    if depth == "compact":
        return 6
    if depth == "swap":
        return latency(reduction)
    return {"montgomery": 12, "barrett": 11}[reduction]
R_MONT = 1 << 16
NQINV = 3327            # -q^-1 mod 2^16
BARRETT_SHIFT = 7
BARRETT_K = 21
BARRETT_M = 80635       # floor(2^28 / q)
INV2 = (Q + 1) // 2     # 1665


def mont_reduce(p):
    """Montgomery reduction of the product p of two canonical values; result in [0, 2q)."""
    m = ((p & 0xFFFF) * NQINV) & 0xFFFF
    return (p + m * Q) >> 16


def barrett_reduce(p):
    """Barrett reduction; result in [0, 2q)."""
    e = ((p >> BARRETT_SHIFT) * BARRETT_M) >> BARRETT_K
    return p - e * Q


def reduce_fn(reduction):
    return {"montgomery": mont_reduce, "barrett": barrett_reduce}[reduction]


def cond_sub(u):
    return u - Q if u >= Q else u


def half(s):
    """s/2 mod q for canonical s."""
    return (s + Q) >> 1 if s & 1 else s >> 1


def bfly_model(reduction, mode, a, b, z):
    """Bit-exact model of one lane: returns (o0, o1)."""
    if mode == 0:
        t = cond_sub(reduce_fn(reduction)(b * z))
        s = a + t
        d = a - t
        return (s - Q if s >= Q else s), (d + Q if d < 0 else d)
    x = b - a
    x = x + Q if x < 0 else x
    t = cond_sub(reduce_fn(reduction)(x * z))
    return half(cond_sub(a + b)), t


def twiddle_encode(reduction, zeta, inverse):
    """Table entry that ``bfly_model`` expects for a given zeta."""
    z = zeta * (INV2 if inverse else 1)
    if reduction == "montgomery":
        z *= R_MONT
    return z % Q


def emit_butterfly(reduction, depth="deep"):
    """Verilog for the ``mlkem_bfly`` lane module."""
    if depth == "swap":
        return _emit_swap(reduction)
    return _emit_compact(reduction) if depth == "compact" else _emit_deep(reduction)


def _emit_compact(reduction):
    if reduction == "montgomery":
        r3_decl = """\
    reg  [15:0] red3;
    wire [31:0] m_full = p2[15:0] * 16'd3327;           // only the low 16 bits are kept"""
        r3 = "red3 <= m_full[15:0];"
        r4_decl = """\
    wire [31:0] mq    = red3 * 16'd3329;
    wire [31:0] sum_u = {8'd0, p3} + mq;"""
        r4 = "u4 <= sum_u[28:16];"
    else:
        r3_decl = """\
    reg  [12:0] red3;
    wire [33:0] e_full = p2[23:7] * 17'd80635;"""
        r3 = "red3 <= e_full[33:21];"
        r4_decl = """\
    wire [23:0] eq     = red3 * 12'd3329;
    wire [23:0] diff_u = p3 - eq;"""
        r4 = "u4 <= diff_u[12:0];"
    return f"""\
// GENERATED by cmtz.accel.mlkem_ntt.arith -- do not edit.  reduction = {reduction}
// ML-KEM (q = 3329) butterfly lane, {LAT} register stages.
//   mode 0 forward (CT):  o0 = a + b*z,  o1 = a - b*z
//   mode 1 inverse (GS):  o0 = (a + b)/2, o1 = (b - a)*z/2
// Latency: v_out/o0/o1 appear LAT = {LAT} clocks after v_in/mode/a/b/z.  All inputs
// must be canonical (< 3329); z comes from the twiddle table (see arith.twiddle_encode).
module mlkem_bfly (
    input  wire        clk,
    input  wire        rst,
    input  wire        v_in,
    input  wire        mode,
    input  wire [11:0] a,
    input  wire [11:0] b,
    input  wire [11:0] z,
    output wire        v_out,
    output wire [11:0] o0,
    output wire [11:0] o1
);
    localparam [12:0] Q = 13'd3329;

    // valid / mode alignment: one bit per stage, cleared by rst
    reg [{LAT}:1] v_pipe = 0;
    reg [{LAT}:1] m_pipe = 0;
    always @(posedge clk) begin
        if (rst) v_pipe <= 0;
        else     v_pipe <= {{v_pipe[{LAT-1}:1], v_in}};
        m_pipe <= {{m_pipe[{LAT-1}:1], mode}};
    end
    assign v_out = v_pipe[{LAT}];

    // ---- R1 ----
    wire [12:0] bma  = {{1'b0, b}} - {{1'b0, a}};
    wire [12:0] bmaq = bma[12] ? bma + Q : bma;          // (b - a) mod q
    reg  [11:0] x1, z1;
    reg  [12:0] c1;
    always @(posedge clk) begin
        x1 <= mode ? bmaq[11:0] : b;
        z1 <= z;
        c1 <= mode ? ({{1'b0, a}} + {{1'b0, b}}) : {{1'b0, a}};
    end

    // ---- R2: DSP multiply ----
    reg [23:0] p2;
    reg [12:0] c2;
    always @(posedge clk) begin
        p2 <= x1 * z1;
        c2 <= (m_pipe[1] && c1 >= Q) ? c1 - Q : c1;     // (a + b) mod q
    end

    // ---- R3: reduction step 1 ----
    reg [23:0] p3;
    reg [12:0] c3;
{r3_decl}
    always @(posedge clk) begin
        p3 <= p2;
        {r3}
        c3 <= (m_pipe[2] && c2[0]) ? (c2 + Q) >> 1 : (m_pipe[2] ? c2 >> 1 : c2);
    end

    // ---- R4: reduction step 2 -> u4 in [0, 2q) ----
    reg [12:0] u4, c4;
{r4_decl}
    always @(posedge clk) begin
        {r4}
        c4 <= c3;
    end

    // ---- R5: canonicalise ----
    reg [11:0] t5, c5;
    always @(posedge clk) begin
        t5 <= (u4 >= Q) ? u4 - Q : u4;
        c5 <= c4[11:0];
    end

    // ---- R6: butterfly add / sub ----
    wire [12:0] sm = {{1'b0, c5}} + {{1'b0, t5}};
    wire [12:0] df = {{1'b0, c5}} - {{1'b0, t5}};
    reg  [11:0] o0_r, o1_r;
    always @(posedge clk) begin
        o0_r <= m_pipe[5] ? c5 : (sm >= Q ? sm - Q : sm[11:0]);
        o1_r <= m_pipe[5] ? t5 : (df[12] ? df + Q : df[11:0]);
    end
    assign o0 = o0_r;
    assign o1 = o1_r;
endmodule
"""


def _emit_deep(reduction):
    """Deep lane, generated stage by stage.

    The p path (multiplicand -> product -> reduction) and the c path (the value the
    product is added to or subtracted from) are separate register chains of the same
    length.  The c path has slack, so its work is spread thinly; the p path is ordered so
    that no stage holds more than one carry chain plus a mux, and the only multiplier is
    the 12x12 product.  Stage k's registers are named *k; logic that feeds stage k+1
    reads mode as m_pipe[k].
    """
    mont = reduction == "montgomery"
    lat = latency(reduction)
    st = []                                   # (title, declarations, always-body)

    def stage(title, decl, body):
        st.append((title, decl, body))

    # ---- front end: both paths together ----
    stage("b - a and a + b",
          "reg [12:0] t1, s1; reg [11:0] a1, b1, z1;",
          "t1 <= {1'b0, b} - {1'b0, a};\n        s1 <= {1'b0, a} + {1'b0, b};\n        a1 <= a; b1 <= b; z1 <= z;")
    stage("(b - a) + q and (a + b) - q",
          "reg [12:0] t2, tq2, s2, sq2; reg [11:0] a2, b2, z2;",
          "t2 <= t1; tq2 <= t1 + Q; s2 <= s1; sq2 <= s1 - Q;\n        a2 <= a1; b2 <= b1; z2 <= z1;")
    stage("select multiplicand and (a + b) mod q",
          "reg [11:0] x3, z3; reg [12:0] c3;",
          "x3 <= m_pipe[2] ? (t2[12] ? tq2[11:0] : t2[11:0]) : b2;\n"
          "        z3 <= z2;\n"
          "        c3 <= m_pipe[2] ? (sq2[12] ? s2 : sq2) : {1'b0, a2};")
    stage("DSP product; c + q",
          "reg [23:0] p4; reg [12:0] c4, hq4;",
          "p4 <= x3 * z3;\n        c4 <= c3; hq4 <= c3 + Q;")
    stage("halve (inverse): (a + b)/2",
          "reg [23:0] p5; reg [12:0] c5;",
          "p5 <= p4;\n        c5 <= m_pipe[4] ? (c4[0] ? hq4[12:1] : {1'b0, c4[12:1]}) : c4;")
    n = 5

    def delay_c(k):
        return f"reg [12:0] c{k};", f"c{k} <= c{k - 1};"

    if mont:
        stage("m = p * 3327 mod 2^16, step 1  (3327 = 2^11 + 2^10 + 2^8 - 1)",
              "reg [15:0] ms6, mt6; reg [23:0] p6; reg [12:0] c6;",
              "ms6 <= (p5[15:0] << 11) + (p5[15:0] << 10);\n        mt6 <= (p5[15:0] << 8) - p5[15:0];\n        p6 <= p5; c6 <= c5;")
        stage("m",
              "reg [15:0] m7; reg [23:0] p7; reg [12:0] c7;",
              "m7 <= ms6 + mt6; p7 <= p6; c7 <= c6;")
        stage("m*q partial sums (q = 2^11 + 2^10 + 2^8 + 1)",
              "reg [27:0] qa8; reg [24:0] qb8; reg [23:0] p8; reg [12:0] c8;",
              "qa8 <= ({12'd0, m7} << 11) + ({12'd0, m7} << 10);\n        qb8 <= ({9'd0, m7} << 8) + {9'd0, m7};\n        p8 <= p7; c8 <= c7;")
        stage("p + m*q, first half",
              "reg [27:0] ps9; reg [24:0] qb9; reg [12:0] c9;",
              "ps9 <= {4'd0, p8} + qa8; qb9 <= qb8; c9 <= c8;")
        stage("(p + m*q) >> 16, in [0, 2q)",
              "reg [12:0] u10, c10; wire [27:0] sum10 = ps9 + {3'd0, qb9};",
              "u10 <= sum10[27:16]; c10 <= c9;")
        n = 10
        u = "u10"
    else:
        stage("quotient estimate e = ((p >> 7) * 80635) >> 21",
              "wire [33:0] e_full = p5[23:7] * 17'd80635; reg [12:0] e6; reg [23:0] p6; reg [12:0] c6;",
              "e6 <= e_full[33:21]; p6 <= p5; c6 <= c5;")
        stage("e*q partial sums",
              "reg [23:0] ea7; reg [21:0] eb7; reg [23:0] p7; reg [12:0] c7;",
              "ea7 <= ({11'd0, e6} << 11) + ({11'd0, e6} << 10);\n        eb7 <= ({9'd0, e6} << 8) + {9'd0, e6};\n        p7 <= p6; c7 <= c6;")
        stage("p - e*(2^11 + 2^10)",
              "reg [23:0] r8; reg [21:0] eb8; reg [12:0] c8;",
              "r8 <= p7 - ea7; eb8 <= eb7; c8 <= c7;")
        stage("remainder in [0, 2q)",
              "reg [12:0] u9, c9; wire [23:0] r9 = r8 - {2'd0, eb8};",
              "u9 <= r9[12:0]; c9 <= c8;")
        n = 9
        u = "u9"
    # canonicalise: t = u mod q and tm = t - q, from two parallel chains
    k = n + 1
    stage("canonicalise: t = u mod q, tm = t - q",
          f"reg [12:0] t{k}, tm{k}, c{k}; wire [12:0] d1_{k} = {u} - Q; wire [12:0] d2_{k} = {u} - 2 * Q;",
          f"t{k} <= d1_{k}[12] ? {u} : d1_{k};\n        tm{k} <= d1_{k}[12] ? d1_{k} : d2_{k};\n        c{k} <= c{n};")
    assert k + 1 == lat, (k, lat)
    body = []
    for i, (title, decl, code) in enumerate(st, 1):
        body.append(f"    // ---- R{i}: {title} ----\n    {decl}\n    always @(posedge clk) begin\n        {code}\n    end\n")
    kk = k
    return f"""\
// GENERATED by cmtz.accel.mlkem_ntt.arith -- do not edit.  reduction = {reduction}, deep lane
// ML-KEM (q = 3329) butterfly lane, {lat} register stages, one DSP product per lane.
//   mode 0 forward (CT):  o0 = a + b*z,  o1 = a - b*z
//   mode 1 inverse (GS):  o0 = (a + b)/2, o1 = (b - a)*z/2
// Latency: v_out/o0/o1 appear LAT = {lat} clocks after v_in/mode/a/b/z.  All inputs must be
// canonical (< 3329); z comes from the twiddle table (see arith.twiddle_encode).
// Every stage holds at most one carry chain plus a mux; the only multiplier is the single
// 12x12 product (R4).
module mlkem_bfly (
    input  wire        clk,
    input  wire        rst,
    input  wire        v_in,
    input  wire        mode,
    input  wire [11:0] a,
    input  wire [11:0] b,
    input  wire [11:0] z,
    output wire        v_out,
    output wire [11:0] o0,
    output wire [11:0] o1
);
    localparam [12:0] Q = 13'd3329;

    // valid / mode alignment: one bit per stage, cleared by rst
    reg [{lat}:1] v_pipe = 0;
    reg [{lat}:1] m_pipe = 0;
    always @(posedge clk) begin
        if (rst) v_pipe <= 0;
        else     v_pipe <= {{v_pipe[{lat - 1}:1], v_in}};
        m_pipe <= {{m_pipe[{lat - 1}:1], mode}};
    end
    assign v_out = v_pipe[{lat}];

{chr(10).join(body)}
    // ---- R{lat}: output stage, both candidates, select on the sign ----
    reg [11:0] o0_r, o1_r;
    wire [12:0] s0 = c{kk} + t{kk};
    wire [12:0] s1o = c{kk} + tm{kk};                  // c + t - q
    wire [12:0] e1 = c{kk} - t{kk};
    wire [12:0] e2 = c{kk} - tm{kk};                   // c - t + q
    always @(posedge clk) begin
        o0_r <= m_pipe[{lat - 1}] ? c{kk}[11:0] : (s1o[12] ? s0[11:0] : s1o[11:0]);
        o1_r <= m_pipe[{lat - 1}] ? t{kk}[11:0] : (e1[12] ? e2[11:0] : e1[11:0]);
    end
    assign o0 = o0_r;
    assign o1 = o1_r;
endmodule
"""


def _emit_swap(reduction):
    """Diagnostic lane: o0 = b, o1 = a after the deep lane's latency, no arithmetic and no
    DSP.  Used to separate memory / crossbar / control timing from arithmetic timing on the
    board; the expected result of a transform comes from the cycle model."""
    lat = latency(reduction)
    return f"""\
// GENERATED diagnostic lane (swap): o0 = b, o1 = a, {lat} register stages.  Not an NTT lane.
module mlkem_bfly (
    input  wire        clk,
    input  wire        rst,
    input  wire        v_in,
    input  wire        mode,
    input  wire [11:0] a,
    input  wire [11:0] b,
    input  wire [11:0] z,
    output wire        v_out,
    output wire [11:0] o0,
    output wire [11:0] o1
);
    reg [{lat}:1] v_pipe = 0;
    reg [11:0] pa [1:{lat}];
    reg [11:0] pb [1:{lat}];
    integer i;
    always @(posedge clk) begin
        if (rst) v_pipe <= 0;
        else     v_pipe <= {{v_pipe[{lat - 1}:1], v_in}};
        pa[1] <= a; pb[1] <= b;
        for (i = 2; i <= {lat}; i = i + 1) begin pa[i] <= pa[i-1]; pb[i] <= pb[i-1]; end
    end
    assign v_out = v_pipe[{lat}];
    assign o0 = pb[{lat}];
    assign o1 = pa[{lat}];
endmodule
"""
