"""UART front end for cmtz-core, and a whole-design testbench.

The protocol is documented in `cmtz/isa/host.py`, which is also the host
implementation; the testbench generator here builds its byte streams with
the same encoders and takes expected replies from `isa/sim.py`.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from ..isa import host
from ..isa.image import CoreConfig, ProgramImage
from ..isa.sim import ERROR, HALTED, Machine
from .isa_core import _bits

MODULES = Path(__file__).resolve().parent / "verilog_uart_modules.v"


@dataclass
class CoreUart:
    source: str          # uart_rx, uart_tx and the wrapper top (core separate)
    top_name: str


def emit_core_uart(core: CoreConfig, top_name: str = "cmtz_core_uart",
                   core_name: str = "cmtz_core", step: bool = False) -> CoreUart:
    """The UART front end. `step=True` is for a core built with
    `emit_core(step=True)` and adds 'H' (pause) and 'N' (one step), lets 'G'
    resume a paused core, answers 'S' and 'M' while paused, and reports status
    4 (paused) in 'Q'; LED 0 blinks while paused. Default output unchanged."""
    p, q, rw = core.p, core.q, core.rw
    if q > 254:
        raise ValueError("the UART protocol needs q <= 254 (one byte per "
                         "value, 0xFF for errors)")
    pcw = _bits(core.pmem_size)
    paw = _bits(core.pmem_size - 1)
    daw = _bits(core.dmem_size - 1)
    info_const = host.info_frame(core, None)[:15]
    info_hex = info_const.hex()
    if step:
        step_note = ("// Step build: 'H' pause, 'N' one step, 'G' resumes a paused core;\n"
                     "// 'Q' status 4 = paused, LED 0 blinks while paused.\n")
        step_regs = ("reg pause_req = 1'b0, step_req = 1'b0, resume_req = 1'b0;\n"
                     "wire paused;\n")
        step_conn = ("\n    .pause_req(pause_req), .step_req(step_req), "
                     ".resume_req(resume_req), .paused(paused),")
        step_clear = " pause_req <= 1'b0; step_req <= 1'b0; resume_req <= 1'b0;"
        run_decl = ("wire [7:0] status_b = paused ? 8'd4 : {6'd0, status};\n"
                    "reg [23:0] blink = 24'd0;\n"
                    "always @(posedge clk) blink <= blink + 24'd1;\n"
                    "wire led_run = running && (!paused || blink[23]);\n")
        snap_status, led_run, rd_ok = "status_b", "led_run", "(!running || paused)"
        cmd_extra = ', "H", "N"'
        g_block = f"""        "G": if (paused) begin
            resume_req <= 1'b1; code <= 8'h00;
        end else if (!running && cfg_len != {pcw}'d0) begin
            start <= 1'b1; code <= 8'h00;
        end else code <= 8'hFF;
        "H": if (cfg_len != {pcw}'d0) begin
            pause_req <= 1'b1; code <= 8'h00;
        end else code <= 8'hFF;
        "N": if (paused) begin
            step_req <= 1'b1; code <= 8'h00;
        end else code <= 8'hFF;
"""
    else:
        step_note = step_regs = step_conn = step_clear = run_decl = ""
        snap_status, led_run, rd_ok = "6'd0, status", "running", "!running"
        cmd_extra = ""
        g_block = f"""        "G": if (!running && cfg_len != {pcw}'d0) begin
            start <= 1'b1; code <= 8'h00;
        end else code <= 8'hFF;
"""
    src = MODULES.read_text() + f"""

// UART front end for {core_name}: F_{p}, q = {q}, ISA version {core.isa_version}.
// Generated by cmtz/backends/isa_uart.py; protocol in cmtz/isa/host.py.
// LEDs (active low): 0 running, 1 halted, 2 error, 3 toggles per
// interrupt, 4 program loaded, 5 last reply was an error.
{step_note}module {top_name} #(
    parameter CLKS_PER_BIT = 234,           // 27 MHz / 115200
    parameter TIMEOUT_CLKS = 2700000        // 100 ms
) (
    input  wire       clk,
    input  wire       rx,
    output wire       tx,
    output wire [5:0] leds
);

wire [7:0] rx_data;
wire       rx_stb;
reg  [7:0] tx_data = 8'd0;
reg        tx_start = 1'b0;
wire       tx_busy;
uart_rx #(.CLKS_PER_BIT(CLKS_PER_BIT)) u_rx (
    .clk(clk), .rx(rx), .data(rx_data), .strobe(rx_stb));
uart_tx #(.CLKS_PER_BIT(CLKS_PER_BIT)) u_tx (
    .clk(clk), .data(tx_data), .start(tx_start), .tx(tx), .busy(tx_busy));

reg start = 1'b0, abort = 1'b0, irq = 1'b0;
{step_regs}reg [{pcw - 1}:0] cfg_len = {pcw}'d0, cfg_entry = {pcw}'d0, cfg_handler = {pcw}'d0;
reg cfg_has_handler = 1'b0;
reg pm_we = 1'b0;
reg [{paw - 1}:0] pm_addr = {paw}'d0;
reg [31:0] pm_wdata = 32'd0;
reg dm_we = 1'b0;
reg [{daw - 1}:0] dm_addr = {daw}'d0;
reg [{rw - 1}:0] dm_wdata = {rw}'d0;
wire [{rw - 1}:0] dm_rdata;
reg r_we = 1'b0;
reg [4:0] r_addr = 5'd0;
reg [{rw - 1}:0] r_wdata = {rw}'d0;
wire [{rw - 1}:0] r_rdata;
reg [3:0] x_addr = 4'd0;
wire [15:0] x_rdata;
wire [1:0] status;
wire [2:0] error;
wire [31:0] retired, disp_retired;
wire [{pcw - 1}:0] disp_pc, pc_out;
wire [15:0] disp_count;
wire boundary;

{core_name} core (
    .clk(clk), .start(start), .abort(abort), .irq(irq),{step_conn}
    .cfg_len(cfg_len), .cfg_entry(cfg_entry), .cfg_handler(cfg_handler),
    .cfg_has_handler(cfg_has_handler),
    .pm_we(pm_we), .pm_addr(pm_addr), .pm_wdata(pm_wdata),
    .dm_we(dm_we), .dm_addr(dm_addr), .dm_wdata(dm_wdata), .dm_rdata(dm_rdata),
    .r_we(r_we), .r_addr(r_addr), .r_wdata(r_wdata), .r_rdata(r_rdata),
    .x_addr(x_addr), .x_rdata(x_rdata),
    .status(status), .error(error), .retired(retired),
    .disp_retired(disp_retired), .disp_pc(disp_pc), .disp_count(disp_count),
    .boundary(boundary), .pc_out(pc_out));

wire running = (status == 2'd1);
{run_decl}
function [31:0] crc8;                       // zlib crc32, one byte
    input [31:0] c;
    input [7:0]  d;
    integer k;
    reg [31:0] x;
    begin
        x = c ^ {{24'd0, d}};
        for (k = 0; k < 8; k = k + 1)
            x = x[0] ? ((x >> 1) ^ 32'hEDB88320) : (x >> 1);
        crc8 = x;
    end
endfunction

localparam C_WAIT = 3'd0, C_ARGS = 3'd1, C_EXEC = 3'd2, C_STREAM = 3'd3,
           C_DONE = 3'd4, C_REPLY = 3'd5;
localparam R_SET = 3'd0, R_S1 = 3'd1, R_S2 = 3'd2, R_SEND = 3'd3,
           R_HOLD = 3'd4, R_WAIT = 3'd5;

reg [2:0]  cs = C_WAIT;
reg [2:0]  rs = R_SET;
reg [7:0]  cmd = 8'd0;
reg [7:0]  arg0 = 8'd0, arg1 = 8'd0, arg2 = 8'd0, arg3 = 8'd0,
           arg4 = 8'd0, arg5 = 8'd0;
reg [2:0]  argi = 3'd0, nargs = 3'd0;
reg [31:0] tcount = 32'd0;
reg [15:0] cnt = 16'd0;
reg [15:0] idx = 16'd0;
reg [15:0] rlen = 16'd0;
reg [1:0]  bsel = 2'd0;
reg        ok = 1'b0, bad = 1'b0, err_led = 1'b0;
reg [7:0]  code = 8'd0;
reg [31:0] crc = 32'hFFFFFFFF;
reg [31:0] words_crc = 32'd0;
reg [127:0] snap = 128'd0;

wire [15:0] a01 = {{arg0, arg1}};
wire [15:0] a23 = {{arg2, arg3}};
wire [15:0] a45 = {{arg4, arg5}};
wire [16:0] dm_end = {{1'b0, a01}} + {{1'b0, a23}};

wire [167:0] info = {{120'h{info_hex}, {{{16 - pcw}'d0, cfg_len}}, words_crc}};
wire [39:0]  p_reply = ok ? {{8'h00, words_crc}} : 40'hFFFFFFFFFF;

reg [7:0] rbyte;
always @* begin
    case (cmd)
    "M":     rbyte = ok ? {{{8 - rw}'d0, dm_rdata}} : 8'hFF;
    "S":     rbyte = !ok ? 8'hFF :
                     (idx < 16'd32) ? {{{8 - rw}'d0, r_rdata}} :
                     (idx[0] ? x_rdata[7:0] : x_rdata[15:8]);
    "Q":     rbyte = snap[127 - 8 * idx[3:0] -: 8];
    "I":     rbyte = info[167 - 8 * idx[4:0] -: 8];
    "P":     rbyte = p_reply[39 - 8 * idx[2:0] -: 8];
    default: rbyte = code;
    endcase
end

always @(posedge clk) begin
    start <= 1'b0; abort <= 1'b0; irq <= 1'b0;{step_clear}
    pm_we <= 1'b0; dm_we <= 1'b0; r_we <= 1'b0; tx_start <= 1'b0;
    case (cs)
    C_WAIT: if (rx_stb) begin
        cmd <= rx_data; argi <= 3'd0; tcount <= 32'd0;
        case (rx_data)
        "P":         begin nargs <= 3'd6; cs <= C_ARGS; end
        "W":         begin nargs <= 3'd2; cs <= C_ARGS; end
        "D", "M":    begin nargs <= 3'd4; cs <= C_ARGS; end
        "I", "S", "G", "Q", "T", "X"{cmd_extra}: cs <= C_EXEC;
        default: ;
        endcase
    end
    C_ARGS: if (rx_stb) begin
        case (argi)
        3'd0: arg0 <= rx_data;
        3'd1: arg1 <= rx_data;
        3'd2: arg2 <= rx_data;
        3'd3: arg3 <= rx_data;
        3'd4: arg4 <= rx_data;
        default: arg5 <= rx_data;
        endcase
        argi <= argi + 3'd1;
        tcount <= 32'd0;
        if (argi + 3'd1 == nargs) cs <= C_EXEC;
    end else if (tcount >= TIMEOUT_CLKS) cs <= C_WAIT;
    else tcount <= tcount + 32'd1;
    C_EXEC: begin
        idx <= 16'd0; rs <= R_SET; rlen <= 16'd1; bad <= 1'b0; tcount <= 32'd0;
        cs <= C_REPLY;
        case (cmd)
        "P": begin
            ok <= !running && a01 != 16'd0 && a01 <= 16'd{core.pmem_size}
                  && a23 < a01 && (a45 == 16'hFFFF || a45 < a01);
            cnt <= a01; bsel <= 2'd0; crc <= 32'hFFFFFFFF; rlen <= 16'd5;
            cs <= (a01 == 16'd0) ? C_DONE : C_STREAM;
        end
        "D": begin
            ok <= !running && dm_end <= 17'd{core.dmem_size};
            cnt <= a23;
            cs <= (a23 == 16'd0) ? C_DONE : C_STREAM;
        end
        "W": if (!running && arg0 < 8'd32 && arg1 < 8'd{q}) begin
            r_addr <= arg0[4:0]; r_wdata <= arg1[{rw - 1}:0]; r_we <= 1'b1;
            code <= 8'h00;
        end else code <= 8'hFF;
        "M": begin
            ok <= {rd_ok} && dm_end <= 17'd{core.dmem_size};
            rlen <= a23;
            if (a23 == 16'd0) cs <= C_WAIT;
        end
        "S": begin ok <= {rd_ok}; rlen <= 16'd64; end
        "Q": begin
            snap <= {{{snap_status}, 5'd0, error, retired, disp_count, disp_retired,
                     {{{16 - pcw}'d0, disp_pc}}, {{{16 - pcw}'d0, pc_out}}}};
            rlen <= 16'd16;
        end
        "I": rlen <= 16'd21;
{g_block}        "T": begin irq <= 1'b1; code <= 8'h00; end
        default: begin abort <= 1'b1; code <= 8'h00; end      // "X"
        endcase
    end
    C_STREAM: if (rx_stb) begin
        tcount <= 32'd0;
        if (cmd == "P") begin
            pm_wdata <= {{pm_wdata[23:0], rx_data}};
            crc <= crc8(crc, rx_data);
            bsel <= bsel + 2'd1;
            if (bsel == 2'd3) begin
                pm_addr <= idx[{paw - 1}:0];
                pm_we <= ok;
                idx <= idx + 16'd1;
                cnt <= cnt - 16'd1;
                if (cnt == 16'd1) cs <= C_DONE;
            end
        end else begin                                         // "D"
            dm_addr <= a01[{daw - 1}:0] + idx[{daw - 1}:0];
            dm_wdata <= rx_data[{rw - 1}:0];
            dm_we <= ok && rx_data < 8'd{q};
            if (rx_data >= 8'd{q}) bad <= 1'b1;
            idx <= idx + 16'd1;
            cnt <= cnt - 16'd1;
            if (cnt == 16'd1) cs <= C_DONE;
        end
    end else if (tcount >= TIMEOUT_CLKS) cs <= C_WAIT;
    else tcount <= tcount + 32'd1;
    C_DONE: begin
        idx <= 16'd0; rs <= R_SET;
        if (cmd == "P") begin
            if (ok) begin
                cfg_len <= a01[{pcw - 1}:0];
                cfg_entry <= a23[{pcw - 1}:0];
                cfg_handler <= a45[{pcw - 1}:0];
                cfg_has_handler <= (a45 != 16'hFFFF);
                words_crc <= ~crc;
            end
        end else begin
            code <= (ok && !bad) ? 8'h00 : 8'hFF;
            rlen <= 16'd1;
        end
        cs <= C_REPLY;
    end
    default: case (rs)                                         // C_REPLY
        R_SET: begin
            dm_addr <= a01[{daw - 1}:0] + idx[{daw - 1}:0];
            r_addr <= idx[4:0];
            x_addr <= idx[4:1];         // idx 32 + 2i + b -> X[i]
            rs <= R_S1;
        end
        R_S1: rs <= R_S2;
        R_S2: rs <= R_SEND;
        R_SEND: if (!tx_busy) begin
            tx_data <= rbyte; tx_start <= 1'b1; rs <= R_HOLD;
            if (idx == 16'd0) err_led <= (rbyte == 8'hFF);
        end
        R_HOLD: rs <= R_WAIT;
        default: if (!tx_busy) begin
            if (idx + 16'd1 >= rlen) cs <= C_WAIT;
            else begin idx <= idx + 16'd1; rs <= R_SET; end
        end
    endcase
    endcase
end

assign leds = ~{{err_led, cfg_len != {pcw}'d0, disp_count[0],
                status == 2'd3, status == 2'd2, {led_run}}};

endmodule
"""
    return CoreUart(src, top_name)


# ── testbench ────────────────────────────────────────────────────────────────

@dataclass
class UartCase:
    """A run over the UART: load (optional), inputs, matrices, G, optional
    T straight after G, poll Q, then read registers and output matrices."""
    image: ProgramImage
    name: str = ""
    inputs: dict[str, int] = field(default_factory=dict)
    matrices: dict[str, list[list[int]]] = field(default_factory=dict)
    trigger: bool = False
    # the trigger's landing point is not known (main still running): don't
    # compare the dispatch fields of the status frame
    trigger_lands_anywhere: bool = False


def emit_core_uart_testbench(core: CoreConfig, cases: list[UartCase],
                             top_name: str = "cmtz_core_uart",
                             cpb: int = 8, timeout: int = 6000) -> str:
    """Testbench driving `top_name` through its UART pins with the protocol
    from host.py; expected replies from the simulator. Prints PASS or FAIL.
    """
    L: list[str] = []
    tid = [0]

    def send(data: bytes) -> None:
        for b in data:
            L.append(f"        tx_byte(8'h{b:02x});")

    def expect(data: bytes, mask: Optional[bytes] = None) -> None:
        mask = mask or bytes([0xFF] * len(data))
        for b, m in zip(data, mask):
            L.append(f"        rx_expect(8'h{b:02x}, 8'h{m:02x});")

    def xfer(cmd: bytes, reply: bytes, mask: Optional[bytes] = None) -> None:
        tid[0] += 1
        L.append(f"        step = {tid[0]};   // {cmd[:1].decode()}")
        send(cmd)
        expect(reply, mask)

    R, X, D = [0] * 32, [0] * 16, [0] * core.dmem_size
    loaded: Optional[ProgramImage] = None
    interrupts = 0

    # protocol edge cases first
    xfer(b"I", host.info_frame(core, None))
    xfer(b"G", bytes([host.BAD]))                    # nothing loaded
    L.append("        tx_byte(8'h5a);               // ignored")
    tid[0] += 1
    L.append(f"        step = {tid[0]};   // timeout drops a partial command")
    send(b"W\x01")
    L.append(f"        repeat ({timeout + 100}) @(posedge clk);")
    xfer(b"I", host.info_frame(core, None))

    for c in cases:
        img = c.image
        img.validate(core)
        L.append(f"        // {c.name}")
        m = Machine(core, img)
        m.R, m.X, m.D = list(R), list(X), list(D)
        if loaded is not img:
            xfer(host.cmd_load(img),
                 bytes([host.OK]) + host.words_crc(img.words).to_bytes(4, "big"))
            loaded = img
        for k, v in c.inputs.items():
            xfer(host.cmd_write_reg(img.inputs[k], v), bytes([host.OK]))
        m.set_inputs(c.inputs)
        for k, mat in c.matrices.items():
            xfer(host.cmd_write_data(img.matrices_in[k].addr, sum(mat, [])),
                 bytes([host.OK]))
            m.write_matrix(k, mat)
        xfer(b"G", bytes([host.OK]))
        if c.trigger:
            xfer(b"T", bytes([host.OK]))
        if c.trigger and c.trigger_lands_anywhere:
            # the result must not depend on where it lands; simulate one spot
            base = Machine(core, img)
            base.R, base.X, base.D = list(m.R), list(m.X), list(m.D)
            base.run()
            m.run(irq_at=(base.retired // 2,))
        elif c.trigger:
            m.run(irq_at=(10 ** 9,))        # placeholder; replaced below
            stall = m.retired
            m2 = Machine(core, img)
            m2.R, m2.X, m2.D = list(R), list(X), list(D)
            m2.set_inputs(c.inputs)
            for k, mat in c.matrices.items():
                m2.write_matrix(k, mat)
            m2.run(irq_at=(stall,))
            m = m2
        else:
            m.run()
        if m.status not in (HALTED, ERROR):
            raise ValueError(f"{c.name}: does not finish")
        interrupts += len(m.dispatches)
        st = host.Status(m.status, m.error, m.retired, interrupts,
                         *(m.dispatches[-1] if m.dispatches else (0, 0)),
                         m.pc)
        mask = bytearray([0xFF] * host.STATUS_LEN)
        if c.trigger_lands_anywhere or not m.dispatches:
            mask[8:14] = bytes(6)           # last dispatch fields
        tid[0] += 1
        L.append(f"        step = {tid[0]};   // poll Q")
        L.append("        poll_status;")
        for i, (b, mk) in enumerate(zip(st.frame(), mask)):
            L.append(f"        chk_q({i}, 8'h{b:02x}, 8'h{mk:02x});")
        regs = bytes(m.R) + b"".join(x.to_bytes(2, "big") for x in m.X)
        xfer(b"S", regs)
        for k, slot in img.matrices_out.items():
            n2 = slot.n * slot.n
            xfer(host.cmd_read_data(slot.addr, n2),
                 bytes(m.D[slot.addr:slot.addr + n2]))
        R, X, D = m.R, m.X, m.D

    # refusals
    if loaded is not None:
        xfer(host.cmd_write_reg(1, core.q), bytes([host.BAD]))
        xfer(host.cmd_write_reg(32, 0), bytes([host.BAD]))
        xfer(host.cmd_read_data(core.dmem_size - 1, 2), bytes([0xFF, 0xFF]))
        xfer(host.cmd_write_data(0, [core.q]), bytes([host.BAD]))
        bad = ProgramImage(core.p, core.q, [0], entry=0)
        bad_cmd = bytearray(host.cmd_load(bad))
        bad_cmd[3:5] = (5).to_bytes(2, "big")        # entry outside
        xfer(bytes(bad_cmd), bytes([0xFF] * 5))
        xfer(b"I", host.info_frame(core, loaded))   # previous program kept

    body = "\n".join(L)
    return _tb_shell(top_name, cpb, timeout, body, f"{len(cases)} runs over the UART")


def _tb_shell(top_name: str, cpb: int, timeout: int, body: str, passed: str) -> str:
    """The testbench around a body of UART steps: byte transmitter, a background
    receiver into a FIFO, rx_expect, poll_status (until the core is not
    running) and chk_q."""
    return f"""// UART testbench for {top_name}. Generated by cmtz/backends/isa_uart.py;
// expected replies from cmtz/isa/sim.py. Prints PASS or FAIL.
`timescale 1ns/1ps
module {top_name}_tb;
localparam CPB = {cpb};
reg clk = 0;
always #5 clk = ~clk;
reg rx = 1'b1;
wire tx;
wire [5:0] leds;
{top_name} #(.CLKS_PER_BIT(CPB), .TIMEOUT_CLKS({timeout})) dut (
    .clk(clk), .rx(rx), .tx(tx), .leds(leds));

integer errors = 0, step = 0, i, k, kt;
reg [7:0] got;
reg [7:0] q [0:15];

task tx_byte(input [7:0] b);
    begin
        rx = 1'b0; repeat (CPB) @(posedge clk);
        for (i = 0; i < 8; i = i + 1) begin
            rx = b[i]; repeat (CPB) @(posedge clk);
        end
        rx = 1'b1; repeat (CPB + 2) @(posedge clk);
    end
endtask

// a free-running receiver: the core may start replying before the request's
// stop bit is over, so replies are decoded in the background into a FIFO
reg [7:0] fifo [0:8191];
integer wp = 0, rp = 0, mb;
reg [7:0] mbyte;
always begin : monitor
    @(negedge tx);
    repeat (CPB / 2) @(posedge clk);
    if (tx == 1'b0) begin
        for (mb = 0; mb < 8; mb = mb + 1) begin
            repeat (CPB) @(posedge clk); mbyte[mb] = tx;
        end
        repeat (CPB) @(posedge clk);
        fifo[wp % 8192] = mbyte; wp = wp + 1;
    end
end

task rx_byte;
    begin : rxb
        kt = 0;
        while (rp >= wp) begin
            @(posedge clk); kt = kt + 1;
            if (kt > 400000) begin
                $display("FAIL: step %0d no reply byte", step);
                errors = errors + 1; got = 8'hxx; disable rxb;
            end
        end
        got = fifo[rp % 8192]; rp = rp + 1;
    end
endtask

task rx_expect(input [7:0] want, input [7:0] mask);
    begin
        rx_byte;
        if (((got ^ want) & mask) !== 8'h00) begin
            $display("FAIL: step %0d got %02x expected %02x", step, got, want);
            errors = errors + 1;
        end
    end
endtask

task poll_status;
    begin : poll
        repeat (200) begin
            tx_byte("Q");
            for (k = 0; k < 16; k = k + 1) begin rx_byte; q[k] = got; end
            if (q[0] != 8'd1) disable poll;
        end
        $display("FAIL: step %0d still running", step);
        errors = errors + 1;
    end
endtask

task chk_q(input integer n, input [7:0] want, input [7:0] mask);
    if (((q[n] ^ want) & mask) !== 8'h00) begin
        $display("FAIL: step %0d status byte %0d = %02x expected %02x",
                 step, n, q[n], want);
        errors = errors + 1;
    end
endtask

initial begin
    repeat (20) @(posedge clk);
{body}
    if (errors == 0) $display("PASS: {passed}");
    else $display("FAIL: %0d errors", errors);
    $finish;
end
endmodule
"""


def standard_uart_cases(core: CoreConfig, examples_dir, seed: int = 0) -> list[UartCase]:
    """Runs over the UART: compiled examples (two in a row on one load, so
    the second sees the first one's leftovers), matpow, interrupts on
    WAITI and mid-loop, and an exhaustive MUL sweep."""
    import random

    from ..compiler import compile_program
    from ..isa.demos import alu_sweep, catalytic_loop
    from .isa_backend import emit_isa

    rng = random.Random(seed)
    p = core.p
    cases: list[UartCase] = []

    def prog(name: str):
        r = compile_program((Path(examples_dir) / name).read_text(),
                            backend="python")
        assert r.ok, r.errors
        return r.ir_program

    for name in ["08_ntt_butterfly.cmtz", "10_fermat_little.cmtz",
                 "fibonacci_pure.cmtz"]:
        b = emit_isa(prog(name), core)
        for _ in range(2):
            cases.append(UartCase(b.image, name,
                                  {k: rng.randrange(p) for k in b.inputs}))
    b = emit_isa(prog("fibonacci.cmtz"), core, matrix_dims={"fib_matrix": 3})
    for _ in range(2):
        cases.append(UartCase(b.image, "fibonacci matpow 3x3", matrices={
            "fib_matrix": [[rng.randrange(p) for _ in range(3)]
                           for _ in range(3)]}))
    for name in ["05_interrupt.cmtz", "09_interrupt_handler.cmtz"]:
        b = emit_isa(prog(name), core)
        cases.append(UartCase(b.image, name + " T on WAITI",
                              {k: rng.randrange(p) for k in b.inputs},
                              trigger=True))
    loop = catalytic_loop(outer=40, inner=20)
    cases.append(UartCase(loop, "catalytic loop, no T", {"x": 6}))
    cases.append(UartCase(loop, "catalytic loop, T mid-run", {"x": 6},
                          trigger=True, trigger_lands_anywhere=True))
    cases.append(UartCase(alu_sweep(core, "MUL"), "MUL sweep"))
    return cases


# ── step build: whole-design testbench ──────────────────────────────────────

@dataclass
class StepCase:
    """Debugger actions over the UART, replayed on the simulator.

    `plan` items: ("N", n) n steps; ("until_wait",) steps until the core is
    stalled on WAITI; ("until_done",) steps until it halts or fails;
    ("T",) an interrupt while paused; ("G",) resume and let it finish.
    Every case starts with 'H' on an idle core. `midrun` replaces the plan:
    'G', then 'H' while it runs (where it stops is not known, so only the
    status is checked there), three steps, then 'G' to the end; the final
    state must be the uninterrupted run's."""
    image: ProgramImage
    name: str = ""
    inputs: dict[str, int] = field(default_factory=dict)
    matrices: dict[str, list[list[int]]] = field(default_factory=dict)
    plan: list[tuple] = field(default_factory=list)
    midrun: bool = False


def emit_core_step_testbench(core: CoreConfig, cases: list[StepCase],
                             top_name: str = "cmtz_core_uart",
                             cpb: int = 8, timeout: int = 6000) -> str:
    """Testbench for a step build (`emit_core_uart(step=True)`): after every
    'N' the status frame and all 64 register bytes are compared with
    `Machine.step()`'s. Prints PASS or FAIL."""
    from ..isa.sim import RUNNING

    L: list[str] = []
    tid = [0]

    def send(data: bytes) -> None:
        for b in data:
            L.append(f"        tx_byte(8'h{b:02x});")

    def expect(data: bytes, mask: Optional[bytes] = None) -> None:
        mask = mask or bytes([0xFF] * len(data))
        for b, m in zip(data, mask):
            L.append(f"        rx_expect(8'h{b:02x}, 8'h{m:02x});")

    def xfer(cmd: bytes, reply: bytes, mask: Optional[bytes] = None,
             note: str = "") -> None:
        tid[0] += 1
        L.append(f"        step = {tid[0]};   // {cmd[:1].decode()} {note}".rstrip())
        send(cmd)
        expect(reply, mask)

    interrupts = [0]            # dispatches over earlier cases (disp_count never resets)

    def frame(m: Machine) -> tuple[bytes, bytearray]:
        shown = 4 if m.status == RUNNING else m.status
        st = host.Status(shown, m.error, m.retired, interrupts[0] + len(m.dispatches),
                         *(m.dispatches[-1] if m.dispatches else (0, 0)), m.pc)
        mask = bytearray([0xFF] * host.STATUS_LEN)
        if not m.dispatches:
            mask[8:14] = bytes(6)           # no dispatch this run: stale fields
        return st.frame(), mask

    def check(m: Machine, what: str, full: bool = True) -> None:
        fr, mask = frame(m)
        if not full:                        # only the status and error bytes
            mask = bytearray([0xFF, 0xFF]) + bytearray(host.STATUS_LEN - 2)
        tid[0] += 1
        L.append(f"        step = {tid[0]};   // poll Q {what}")
        L.append("        poll_status;")
        for i, (b, mk) in enumerate(zip(fr, mask)):
            L.append(f"        chk_q({i}, 8'h{b:02x}, 8'h{mk:02x});")
        if full:
            regs = bytes(m.R) + b"".join(x.to_bytes(2, "big") for x in m.X)
            xfer(b"S", regs, note=what)

    def finish(m: Machine) -> None:
        for _ in range(1_000_000):
            if m.status != RUNNING:
                return
            if m.waiting and not m.pending:
                raise ValueError("a resumed program stalls on WAITI with no trigger")
            m.step()
        raise ValueError("does not finish")

    # protocol edge cases first: nothing loaded
    xfer(b"H", bytes([host.BAD]), note="nothing loaded")
    xfer(b"N", bytes([host.BAD]), note="not paused")

    R, X, D = [0] * 32, [0] * 16, [0] * core.dmem_size
    loaded: Optional[ProgramImage] = None
    for c in cases:
        img = c.image
        img.validate(core)
        L.append(f"        // {c.name}")
        m = Machine(core, img)
        m.R, m.X, m.D = list(R), list(X), list(D)
        if loaded is not img:
            xfer(host.cmd_load(img),
                 bytes([host.OK]) + host.words_crc(img.words).to_bytes(4, "big"))
            loaded = img
        for k, v in c.inputs.items():
            xfer(host.cmd_write_reg(img.inputs[k], v), bytes([host.OK]))
        m.set_inputs(c.inputs)
        for k, mat in c.matrices.items():
            xfer(host.cmd_write_data(img.matrices_in[k].addr, sum(mat, [])),
                 bytes([host.OK]))
            m.write_matrix(k, mat)

        if c.midrun:
            xfer(b"G", bytes([host.OK]))
            xfer(b"H", bytes([host.OK]), note="while running")
            full = Machine(core, img)
            full.R, full.X, full.D = list(m.R), list(m.X), list(m.D)
            full.run()
            m.start()
            check(m, "paused somewhere in the run", full=False)
            for _ in range(3):
                xfer(b"N", bytes([host.OK]))
                check(m, "step after a mid-run pause", full=False)
            xfer(b"G", bytes([host.OK]), note="resume")
            m = full
        else:
            # a probe value in the last two data words, to read back while paused
            probe = core.dmem_size - 2
            xfer(host.cmd_write_data(probe, [3, 5]), bytes([host.OK]))
            m.D[probe:probe + 2] = [3, 5]
            xfer(b"H", bytes([host.OK]), note="idle -> paused at the entry")
            m.start()
            check(m, "at the entry")
            # while paused the program and registers are protected, memory is readable
            xfer(host.cmd_write_reg(1, 0), bytes([host.BAD]), note="refused while paused")
            xfer(host.cmd_read_data(probe, 2), bytes([3, 5]), note="readable while paused")
            xfer(b"H", bytes([host.OK]), note="again, still paused")
            for item in c.plan:
                kind = item[0]
                if kind == "N":
                    for _ in range(item[1]):
                        assert m.status == RUNNING, f"{c.name}: plan steps past the end"
                        xfer(b"N", bytes([host.OK]))
                        m.step()
                        check(m, f"after {m.retired} retired")
                elif kind in ("until_wait", "until_done"):
                    for _ in range(100_000):
                        assert m.status == RUNNING, f"{c.name}: {kind} past the end"
                        xfer(b"N", bytes([host.OK]))
                        m.step()
                        check(m, f"after {m.retired} retired")
                        if kind == "until_wait" and m.waiting:
                            break
                        if kind == "until_done" and m.status != RUNNING:
                            break
                    else:
                        raise ValueError(f"{c.name}: {kind} never ends")
                elif kind == "T":
                    xfer(b"T", bytes([host.OK]), note="while paused")
                    m.pending = True
                elif kind == "G":
                    xfer(b"G", bytes([host.OK]), note="resume")
                    finish(m)
        check(m, "final")
        interrupts[0] += len(m.dispatches)
        if m.status == RUNNING:
            raise ValueError(f"{c.name}: plan ends with the core still paused")
        for k, slot in img.matrices_out.items():
            n2 = slot.n * slot.n
            xfer(host.cmd_read_data(slot.addr, n2),
                 bytes(m.D[slot.addr:slot.addr + n2]))
        xfer(b"N", bytes([host.BAD]), note="finished cores are not paused")
        R, X, D = m.R, m.X, m.D

    body = "\n".join(L)
    text = _tb_shell(top_name, cpb, timeout, body,
                     f"{len(cases)} stepped runs over the UART")
    return (text.replace("// UART testbench for", "// UART step testbench for", 1)
                .replace(f"module {top_name}_tb;", f"module {top_name}_step_tb;", 1))


def standard_step_cases(core: CoreConfig, examples_dir, seed: int = 0) -> list[StepCase]:
    """Straight-line stepping, a looping matpow, an interrupt taken while
    paused on WAITI and in a handler, and a pause in the middle of a run."""
    import random

    from ..compiler import compile_program
    from ..isa.demos import catalytic_loop
    from .isa_backend import emit_isa

    rng = random.Random(seed)
    p = core.p

    def prog(name: str):
        r = compile_program((Path(examples_dir) / name).read_text(), backend="python")
        assert r.ok, r.errors
        return r.ir_program

    cases: list[StepCase] = []
    b = emit_isa(prog("fibonacci_pure.cmtz"), core)
    cases.append(StepCase(b.image, "fibonacci_pure, every step",
                          {k: rng.randrange(p) for k in b.inputs},
                          plan=[("until_done",)]))
    b = emit_isa(prog("08_ntt_butterfly.cmtz"), core)
    cases.append(StepCase(b.image, "ntt_butterfly, 4 steps then resume",
                          {k: rng.randrange(p) for k in b.inputs},
                          plan=[("N", 4), ("G",)]))
    b = emit_isa(prog("fibonacci.cmtz"), core, matrix_dims={"fib_matrix": 3})
    cases.append(StepCase(b.image, "fibonacci matpow 3x3, 60 steps then resume",
                          matrices={"fib_matrix": [[rng.randrange(p) for _ in range(3)]
                                                   for _ in range(3)]},
                          plan=[("N", 60), ("G",)]))
    for name in ["05_interrupt.cmtz", "09_interrupt_handler.cmtz"]:
        b = emit_isa(prog(name), core)
        cases.append(StepCase(
            b.image, name + ": step to WAITI, T while paused, step through the handler",
            {k: rng.randrange(p) for k in b.inputs},
            plan=[("until_wait",), ("N", 2), ("T",), ("until_done",)]))
    loop = catalytic_loop(outer=40, inner=20)
    cases.append(StepCase(loop, "catalytic loop, paused mid-run", {"x": 6}, midrun=True))
    return cases
