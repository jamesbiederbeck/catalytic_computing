"""Multilane cmtz-core RTL (RFC-003 phases A1 and A2), its UART front end,
and testbenches checked against the multilane model (`isa/multicore.py`).

`emit_mlane(core, lanes, lease=False)` instantiates `lanes` unmodified
`cmtz_core` modules side by side, each with its own program memory, data
memory, registers and control: independent instruction streams that share
the clock and nothing else. With `lease=True` the lanes are the lane
variant of the same generator (`emit_core(..., lane=True)`); their field
registers live here, in one physical array, which is what a lease needs:

  RF[32 l + r]     lane l's register r
  lease of lane b  state (none, active, poisoned), owner, bank (1..3) and
                   count (1..8): lane b's R24 .. R24+count-1 are the owner's
                   R(8 bank) .. R(8 bank + count - 1), the same flip-flops
  owner stall      a lane in EXEC whose instruction names (per
                   `encoding.FORMATS`) one of its own registers held by an
                   active or poisoned lease is held in EXEC
  acquire          host command only, both lanes idle; refused if a lane
                   would lend and borrow at once, the bank is taken, or a
                   leased register holds a value outside [0, p)
  release          when the borrower's status leaves running: halted
                   releases (the owner may use the registers from the next
                   cycle on, as in the model), anything else poisons

Writes from a lane are registered and land one cycle after EXEC, at the
physical register translated in EXEC; the next instruction reads in its
own EXEC at least two cycles later, so this costs no cycles.

Per lane the block keeps cycle stamps from a free-running counter: the
first and the last+1 running cycle of the last run (their difference is
the run's cycle count, which the model predicts exactly) and the cycles
spent stalled. This is the on-chip measurement of instructions per clock.
"""

