"""Generate a Tang Nano 20K apio project for the ML-KEM NTT accelerator.

Usage: uv run python examples/fpga/build_mlkem_ntt.py <output-dir> --lanes N [options]
  e.g. <playground>/projects   ->   <output-dir>/mlkem-ntt-l4[-<suffix>]/

Options:
  --lanes {1,2,4,8}     parallel butterfly lanes (default 1)
  --reduction {montgomery,barrett}
  --bank-ram {block,lut}
  --pll IDIV,FBDIV,ODIV rPLL settings (core clock = 27 MHz * (FBDIV+1)/(IDIV+1)); default: no PLL
  --freq MHZ            nextpnr timing target recorded in apio.ini
  --noalu               yosys -noalu (see the tang-nano-20k CLAUDE.md)
  --suffix S            appended to the project name

Everything in the project is generated; edit cmtz/accel/mlkem_ntt/ and regenerate.
GENERATED.txt records the generator commit and configuration.  No board access.
"""
import argparse
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))

from cmtz.accel.mlkem_ntt import arith, rtlgen, tb_bfly, tb_core, tb_uart, uart_top
from cmtz.accel.mlkem_ntt.config import NTTConfig

PINS = """\
IO_LOC "clk27" 4;
IO_PORT "clk27" IO_TYPE=LVCMOS33 PULL_MODE=NONE;
IO_LOC "tx" 69;
IO_PORT "tx" IO_TYPE=LVCMOS33 PULL_MODE=UP;
IO_LOC "rx" 70;
IO_PORT "rx" IO_TYPE=LVCMOS33 PULL_MODE=UP;
""" + "".join(f'IO_LOC "leds[{i}]" {15 + i};\n' for i in range(6)) + \
    "".join(f'IO_PORT "leds[{i}]" IO_TYPE=LVCMOS33;\n' for i in range(6))


def git_rev(repo):
    try:
        rev = subprocess.run(["git", "-C", str(repo), "rev-parse", "--short", "HEAD"],
                             capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "-C", str(repo), "status", "--porcelain", "--",
                                "cmtz/accel", "examples/fpga/build_mlkem_ntt.py"],
                               capture_output=True, text=True).stdout.strip()
        return rev + (" (generator files modified)" if dirty else "")
    except Exception:
        return "unknown"


def build(out_dir: Path, cfg: NTTConfig, suffix="", freq=None, noalu=False):
    name = f"mlkem-ntt-l{cfg.lanes}" + (f"-{suffix}" if suffix else "")
    d = out_dir / name
    d.mkdir(parents=True, exist_ok=True)
    core, info = rtlgen.emit_core(cfg)
    files = {
        "mlkem_bfly.v": arith.emit_butterfly(cfg.reduction),
        "mlkem_ntt_core.v": core,
        "mlkem_ntt_uart.v": uart_top.emit_top(cfg),
        "mlkem_bfly_tb.v": tb_bfly.emit_bfly_tb(cfg.reduction, stride=211),
        "mlkem_ntt_core_tb.v": tb_core.emit_core_tb(cfg),
        "mlkem_ntt_uart_tb.v": tb_uart.emit_uart_tb(cfg),
        "pins.cst": PINS,
    }
    ini = ["[env:default]", "board = sipeed-tang-nano-20k", "top-module = mlkem_ntt_uart"]
    if noalu:
        ini.append("yosys-extra-options = -noalu")
    if freq:
        ini.append(f"nextpnr-extra-options = --freq {freq}")
    files["apio.ini"] = "\n".join(ini) + "\n"
    for fn, text in files.items():
        (d / fn).write_text(text)
    hz = uart_top.pll_hz(cfg.pll) if cfg.pll else 27e6
    (d / "GENERATED.txt").write_text(
        f"Generated by examples/fpga/build_mlkem_ntt.py (cook_mertz / catalytic_computing)\n"
        f"generator commit : {git_rev(Path(__file__).resolve().parent.parent.parent)}\n"
        f"config           : {cfg}\n"
        f"core clock       : {hz / 1e6:.3f} MHz\n"
        f"forward words    : {info['forward_words']}  (kernel cycles {info['forward_words'] + 2})\n"
        f"inverse words    : {info['inverse_words']}  (kernel cycles {info['inverse_words'] + 2})\n"
        f"control word     : {info['width']} bits x {info['total']} entries\n"
        f"Do not edit the .v files: regenerate them.\n")
    return d


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out_dir", type=Path)
    ap.add_argument("--lanes", type=int, default=1, choices=(1, 2, 4, 8))
    ap.add_argument("--reduction", default="montgomery", choices=("montgomery", "barrett"))
    ap.add_argument("--bank-ram", default="block", choices=("block", "lut"))
    ap.add_argument("--pll", default=None)
    ap.add_argument("--freq", type=float, default=None)
    ap.add_argument("--noalu", action="store_true")
    ap.add_argument("--suffix", default="")
    a = ap.parse_args()
    pll = tuple(int(x) for x in a.pll.split(",")) if a.pll else None
    cfg = NTTConfig(lanes=a.lanes, reduction=a.reduction, bank_ram=a.bank_ram, pll=pll)
    print(build(a.out_dir, cfg, a.suffix, a.freq, a.noalu))
